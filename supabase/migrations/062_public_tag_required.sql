-- =============================================================
-- Migration 062: 登録時の名乗りを飛ばせなくする
--
-- 061 では「あとで決める」を置いた（登録の一歩目で降りられるのを避けるため）が、
-- 飛ばした人は名前も @ID も未設定のまま公開まで到達できる。デスクの公開ページに
-- 投稿者名が出ないのは、公開した本人にとっても見る側にとっても壊れて見える。
-- 名前と @ID は登録の続きとして必ず決めてもらう形にしたので、
-- 「聞かずに印だけ立てる」入口を落とす。
--
-- 通信できないときの逃げ道はアプリ側に置いた（名前は端末に保存して先へ通し、
-- public_tag_chosen は立てずに次の起動でもう一度聞く）。サーバーに
-- 「決めていないのに決めたことにする」関数を残す必要はない。
-- =============================================================

DROP FUNCTION IF EXISTS public.dismiss_public_tag_prompt();

NOTIFY pgrst, 'reload schema';
